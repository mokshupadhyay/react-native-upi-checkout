/**
 * Parameters of a UPI payment request. Each field maps to one query
 * parameter of the `upi://pay` URL (shown in brackets).
 *
 * Check the current NPCI UPI Linking Specifications for the exact rules your
 * use case must follow. This library only applies the shape checks and the
 * conservative defaults described on `validateUpiParams`.
 */
export interface UpiPaymentParams {
  /** Payee virtual payment address, for example `shop@okbank` (`pa`). */
  payeeVpa: string;
  /** Payee name shown in the UPI app (`pn`). */
  payeeName: string;
  /**
   * Amount in rupees, greater than zero with at most two decimals (`am`).
   * Pass a decimal string such as `'149.50'` to avoid floating point surprises.
   * A number is converted with `String(value)`, so `0.1 + 0.2` is rejected
   * instead of being rounded. The URL always carries exactly two decimals.
   */
  amount: string | number;
  /** Currency (`cu`). Only `'INR'` is accepted and it is the default. */
  currency?: UpiCurrency;
  /** Your reference for this order or payment (`tr`). */
  transactionRef: string;
  /** Short description shown to the payer (`tn`). */
  note: string;
  /** Merchant category code, four digits (`mc`). Optional. */
  merchantCode?: string;
  /** Transaction id generated by your PSP, if it gives you one (`tid`). Optional. */
  transactionId?: string;
  /** A link with details about the order (`url`). Optional. */
  url?: string;
}

export type UpiCurrency = 'INR';

export type UpiParamField = keyof UpiPaymentParams;

/**
 * - `REQUIRED`: a required value is missing or empty.
 * - `INVALID_TYPE`: the value is not a string (or a number, for `amount`).
 * - `INVALID_VPA`: `payeeVpa` does not look like `name@handle`.
 * - `INVALID_AMOUNT`: not a positive amount with at most two decimals.
 * - `INVALID_CURRENCY`: anything other than `'INR'`.
 * - `INVALID_MERCHANT_CODE`: `merchantCode` is not four digits.
 * - `INVALID_CHARACTERS`: the value cannot be URL-encoded (a lone UTF-16 surrogate).
 * - `TOO_LONG`: longer than the limit in `UpiLimits`.
 */
export type UpiProblemCode =
  | 'REQUIRED'
  | 'INVALID_TYPE'
  | 'INVALID_VPA'
  | 'INVALID_AMOUNT'
  | 'INVALID_CURRENCY'
  | 'INVALID_MERCHANT_CODE'
  | 'INVALID_CHARACTERS'
  | 'TOO_LONG';

export interface UpiProblem {
  code: UpiProblemCode;
  field: UpiParamField;
  message: string;
}

/**
 * Maximum lengths in characters (Unicode code points).
 *
 * The defaults in `DEFAULT_UPI_LIMITS` are conservative defaults chosen so
 * that common UPI apps accept the request. They are not quoted from the NPCI
 * specification. Check the current UPI Linking Specifications and your PSP's
 * documentation, and override them if you need to.
 */
export interface UpiLimits {
  payeeVpa: number;
  payeeName: number;
  transactionRef: number;
  note: number;
}

export interface UpiValidationOptions {
  /** Override some or all of `DEFAULT_UPI_LIMITS`. */
  limits?: Partial<UpiLimits>;
}

/**
 * - `success`: the UPI app says the payment succeeded.
 * - `failure`: the UPI app says the payment failed.
 * - `submitted`: the UPI app reports `SUBMITTED` or `PENDING`; the outcome is
 *   not known yet.
 * - `unknown`: no recognizable status in the response.
 */
export type UpiResponseStatus = 'success' | 'failure' | 'submitted' | 'unknown';

/**
 * The response string an Android UPI app returns, parsed.
 *
 * This is a CLIENT-SIDE CLAIM. Any app on the device can produce this string,
 * and a user can return to your app before the bank has settled the payment.
 * Never treat it as proof of payment. Confirm the payment on your server, for
 * example with your PSP's status API or a webhook, before you fulfil an order.
 */
export interface UpiResponse {
  status: UpiResponseStatus;
  /** `txnId`: the transaction id assigned by the payer's app or bank. */
  transactionId?: string;
  /** `txnRef`: usually echoes the `transactionRef` you sent. */
  transactionRef?: string;
  /** `responseCode`: a code from the payer's bank or app. */
  responseCode?: string;
  /** `ApprovalRefNo`: the approval reference, when the app sends one. */
  approvalRef?: string;
  /** The unmodified response string. */
  raw: string;
}

/** An installed app that can handle a UPI payment. */
export interface UpiApp {
  /** Display name: the app label on Android, the name in the known apps table on iOS. */
  name: string;
  /** Android package name. Pass it as `pay(params, { packageName })`. Not set on iOS. */
  packageName?: string;
  /** Id in the known apps table (`KNOWN_UPI_APPS`). Pass it as `pay(params, { iosApp })`. Only set on iOS. */
  iosApp?: string;
}

export interface UpiPayOptions extends UpiValidationOptions {
  /**
   * Android: open this app directly instead of showing the system chooser.
   * Ignored on iOS.
   */
  packageName?: string;
  /**
   * iOS: open this app from the known apps table, for example `'phonepe'`.
   * Without it, iOS opens the generic `upi://pay` URL with whichever app the
   * system picks. Ignored on Android.
   */
  iosApp?: string;
  /** Android: title of the system chooser. Ignored when `packageName` is set. */
  chooserTitle?: string;
}

/**
 * The outcome of `pay()`:
 *
 * - `completed` (Android only): the UPI app returned a response. `response`
 *   is a CLIENT-SIDE CLAIM; confirm the payment on your server.
 * - `cancelled` (Android only): the user backed out or the app returned no data.
 * - `launched` (iOS only): the UPI app was opened. iOS gives no result back,
 *   so check the payment status on your server when the user returns.
 * - `unavailable`: no installed app can handle the payment (or the requested
 *   `packageName` / `iosApp` is not installed).
 */
export type UpiPayResult =
  | { kind: 'completed'; response: UpiResponse; resultCode: number }
  | { kind: 'cancelled'; resultCode: number }
  | { kind: 'launched' }
  | { kind: 'unavailable' };

/**
 * Stable codes on `UpiError.code`:
 *
 * - `INVALID_PARAMS`: the parameters or options failed validation; see `problems`.
 * - `NO_UPI_APP`: Android could not start the UPI app although it was found
 *   a moment before (for example it was uninstalled in between). The common
 *   case of no installed app resolves with `kind: 'unavailable'` instead.
 * - `IN_PROGRESS`: another payment is still waiting for its result.
 * - `ACTIVITY_UNAVAILABLE`: Android has no foreground activity to start from,
 *   or the React instance was torn down while waiting for the result.
 * - `NOT_LINKED`: the native module is missing (Expo Go, web, or no rebuild).
 * - `UNKNOWN`: anything else; `message` has the details.
 */
export type UpiErrorCode =
  | 'INVALID_PARAMS'
  | 'NO_UPI_APP'
  | 'IN_PROGRESS'
  | 'ACTIVITY_UNAVAILABLE'
  | 'NOT_LINKED'
  | 'UNKNOWN';
